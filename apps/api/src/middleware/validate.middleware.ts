/**
 * Escapes HTML special characters in string inputs to prevent XSS injection.
 */
export const sanitizeString = (str: string): string => {
  return str
    .trim()
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#x27;");
};
